"""Declared Iceberg schemas for the CFB datasets.

Types mirror the frames cfb_win_probability's ingestion and feature snapshots produce.
team_id is missing for some FCS and defunct teams, so tables keyed per team use the
team name where team_id can be null. cfb_portal has no transfer id; a player's
name, origin school and transfer date identify the row.
"""
import pyarrow as pa
from gnomepy.data import TableSpec

# Head coach seasons with hire date and that season's results (usable only after it ends)
COACHES = TableSpec(
    "cfb_coaches",
    pa.schema([
        pa.field("coach_id", pa.int64(), nullable=False),
        pa.field("first_name", pa.string()),
        pa.field("last_name", pa.string()),
        pa.field("hire_date", pa.timestamp("us", tz="UTC")),
        pa.field("season", pa.int64(), nullable=False),
        pa.field("team_id", pa.int64(), nullable=False),
        pa.field("school", pa.string()),
        pa.field("games", pa.int64()),
        pa.field("wins", pa.int64()),
        pa.field("losses", pa.int64()),
        pa.field("srs", pa.float64()),
        pa.field("sp_overall", pa.float64()),
        pa.field("sp_offense", pa.float64()),
        pa.field("sp_defense", pa.float64()),
        pa.field("preseason_rank", pa.float64()),
        pa.field("postseason_rank", pa.float64()),
        pa.field("results_available_at", pa.timestamp("us", tz="UTC")),
    ]),
    key=("coach_id", "season", "team_id"),
)

